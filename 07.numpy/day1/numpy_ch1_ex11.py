# 1차원 배열 슬라이싱

import numpy as np

# 1차원 배열 슬라이싱 : 리스트의 슬라이싱과 동일
arr = np.arange(10)
print(arr[:])    # 배열 전체 원소 출력, arr[:]와 arr[::] 동일 => 전체 데이터

# 기본 슬라이싱
print(f'처음 5개 : {arr[:5]}')    # [0 1 2 3 4]
print(f'3번째부터 7번째 : {arr[3:7]}')    # [3 4 5 6]
print(f'마지막 3개 : {arr[-3:]}')    # [7 8 9]

# Step 사용
print(f'짝수 인덱스 : {arr[::2]}')    # [0 2 4 6 8]
print(f'홀수 인덱스 : {arr[1::2]}')    # [1 3 5 7 9]  => [1]부터 끝까지 step=2
print(f'역순 : {arr[::-1]}')    # [9 8 7 6 5 4 3 2 1 0]

# 범위와 step 조합
print(f'2부터 8까지 2씩 : {arr[2:8:2]}')    # [2 4 6]